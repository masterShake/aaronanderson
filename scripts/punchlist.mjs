/**
 * The punch list: every open HOLD and pending CONFIRM, read statically from
 * src/content.
 *
 *   npm run punchlist                 print the lists
 *   npm run punchlist -- --json       machine-readable
 *   npm run punchlist -- --write      regenerate PLACEHOLDERS.md (with deployment settings from .env.example)
 *   npm run punchlist -- --ci         one-line summary; with STRICT_HOLDS=1, fail while essentials or CONFIRMs remain
 *   npm run punchlist -- --strict     fail like --ci under STRICT_HOLDS=1
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { ROOT, calls, listTs } from './lib/content-ast.mjs'

const args = new Set(process.argv.slice(2))
const strict = args.has('--strict') || (args.has('--ci') && process.env.STRICT_HOLDS === '1')
const items = listTs('src/content').flatMap((f) => calls(f))
const stray = listTs('src', ['src/content/hold.ts'])
  .filter((f) => !f.includes('/src/content/'))
  .flatMap((f) => calls(f))
const holds = items.filter((i) => i.name === 'hold')
const claims = items.filter((i) => i.name === 'confirm')
const errs = []

const ids = new Map()
for (const i of items) {
  if (!i.id || typeof i.id !== 'string' || /[`$]/.test(i.id))
    errs.push(`${i.file}:${i.line} ${i.name}() needs a literal id`)
  else if (ids.has(i.id))
    errs.push(`duplicate id ${i.id} (${ids.get(i.id)} and ${i.file}:${i.line})`)
  else ids.set(i.id, `${i.file}:${i.line}`)
}
for (const s of stray) errs.push(`${s.file}:${s.line} ${s.name}() outside src/content`)

const MUST_BE_ESSENTIAL = [
  /^site\.email$/,
  /^site\.scheduler\.url$/,
  /^site\.callLength$/,
  /^price\.s0[16]$/,
  /^people\.[^.]+\.name$/,
]
for (const h of holds)
  if (MUST_BE_ESSENTIAL.some((re) => re.test(h.id)) && h.essential !== true)
    errs.push(`${h.id} must be essential: true`)

const essential = holds.filter((h) => h.essential === true)
const optional = holds.filter((h) => h.essential !== true)
const pending = claims.filter((c) => (c.status ?? 'pending') === 'pending')

const short = (v, n = 70) => {
  const s = String(v).replace(/\s+/g, ' ')
  return s.length > n ? `${s.slice(0, n - 1)}…` : s
}
const row = (h) =>
  `  [ ] ${h.id.padEnd(30)} ${String(h.kind ?? '').padEnd(9)} ${h.first}  (${h.file}:${h.line})`
const claimRow = (c) => `  [ ] ${c.id.padEnd(30)} ${short(c.first)}  (${c.file}:${c.line})`

/** "Deployment settings" from .env.example: ## groups, KEY= rows, NOTE: items. */
function deploymentSettings() {
  const lines = readFileSync(join(ROOT, '.env.example'), 'utf8').split('\n')
  const out = []
  for (const line of lines) {
    const group = /^#\s*##\s+(.*)$/.exec(line)
    if (group) {
      out.push(`\n### ${group[1]}\n`)
      continue
    }
    const note = /^#\s*NOTE:\s*(.*)$/.exec(line)
    if (note) {
      out.push(`- [ ] ${note[1]}`)
      continue
    }
    const v = /^(#\s*)?([A-Z][A-Z0-9_]+)=(\S*)\s*(?:#\s*(.*))?$/.exec(line)
    if (v) out.push(`- \`${v[2]}\`${v[1] ? ' (optional)' : ''}${v[4] ? `: ${v[4]}` : ''}`)
  }
  return out.join('\n')
}

function markdown() {
  const table = (rows, cols) =>
    rows.length
      ? [`| ${cols.join(' | ')} |`, `|${cols.map(() => '---').join('|')}|`, ...rows].join('\n')
      : '_None._'
  const holdRows = (list) =>
    list.map((h) => `| \`${h.id}\` | ${h.kind ?? ''} | ${h.first} | ${h.file}:${h.line} |`)
  return `# Placeholders

Generated by \`npm run punchlist -- --write\`. Do not edit by hand: fill the values in
\`src/content\` (and the environment), then regenerate.

- **Essential HOLDs** block a launch: \`STRICT_HOLDS=1\` fails the build while any remain.
- **Pending CONFIRMs** are promises the site makes only once you agree. Set each to
  \`status: 'ok'\` to keep it or \`'cut'\` to drop it.
- Production shows each HOLD's fallback (or nothing) and hides proof until it is real.

## Essential HOLDs (${essential.length})

${table(holdRows(essential), ['ID', 'Kind', 'What is needed', 'Where'])}

## Optional HOLDs (${optional.length})

${table(holdRows(optional), ['ID', 'Kind', 'What is needed', 'Where'])}

## Promises waiting for your CONFIRM (${pending.length})

${table(
  pending.map((c) => `| \`${c.id}\` | ${short(c.first, 120)} | ${c.file}:${c.line} |`),
  ['ID', 'Claim', 'Where'],
)}

## Deployment settings
${deploymentSettings()}
`
}

if (args.has('--json')) {
  console.log(JSON.stringify({ essential, optional, pending, errors: errs }, null, 2))
} else if (args.has('--write')) {
  writeFileSync(join(ROOT, 'PLACEHOLDERS.md'), markdown())
  console.log(
    `PLACEHOLDERS.md: ${essential.length} essential, ${optional.length} optional, ${pending.length} pending CONFIRM`,
  )
} else if (!args.has('--ci')) {
  console.log(`ESSENTIAL HOLDS (${essential.length})\n${essential.map(row).join('\n')}`)
  console.log(`\nHOLDS (${optional.length})\n${optional.map(row).join('\n')}`)
  console.log(`\nCONFIRM, pending (${pending.length})\n${pending.map(claimRow).join('\n')}`)
} else {
  console.log(
    `punchlist: ${essential.length} essential, ${optional.length} optional, ${pending.length} pending CONFIRM${strict ? ' (strict)' : ''}`,
  )
}

if (errs.length) {
  console.error(errs.join('\n'))
  process.exit(1)
}
if (strict && (essential.length || pending.length)) {
  console.error(`\nSTRICT_HOLDS: these block a production build.\n`)
  console.error(`ESSENTIAL HOLDS (${essential.length})\n${essential.map(row).join('\n')}`)
  console.error(`\nCONFIRM, pending (${pending.length})\n${pending.map(claimRow).join('\n')}`)
  console.error(
    '\nFill every essential HOLD and set every CONFIRM to status ok or cut before deploying.',
  )
  process.exit(1)
}
